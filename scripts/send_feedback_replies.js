async function main() {
  const dry = process.argv.includes("--dry");
  for (const item of REPLIES) {
    if (dry) {
      console.log(`[проверка] обращение ${item.id}: ${item.text.slice(0, 60)}…`);
      continue;
    }
    try {
      const result = await replyToFeedback(item.id, item.text);
      console.log(`обращение ${item.id}: отправлено =`, JSON.stringify(result));
    } catch (err) {
      console.error(`обращение ${item.id}: ошибка —`, err && err.message ? err.message : err);
    }
  }
  process.exit(0);
}

main();
